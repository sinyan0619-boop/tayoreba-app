export function addPrefecture(address: string): string {
  if (!address) return address;
  const trimmed = address.trim();

  // すでに都道府県が付いている
  if (PREFS.some((p) => trimmed.startsWith(p))) return trimmed;

  // 長い市区町村名から順にマッチ（「大阪狭山市」が「大阪市」より先にマッチするよう）
  const sorted = Object.keys(CITY_TO_PREF).sort((a, b) => b.length - a.length);
  for (const city of sorted) {
    if (trimmed.startsWith(city)) {
      return CITY_TO_PREF[city] + trimmed;
    }
  }

  return trimmed;
}
